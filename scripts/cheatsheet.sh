#!/usr/bin/env bash
# Generate docs/wiki/cheatsheet.md — every skill, one line each.
#
# The page is derived, never hand-written. Each row is the what-clause of the
# skill's own `description`: everything before the "Use when" trigger, which
# AGENTS.md requires every description to carry. The SKILL.md is the only
# source, so the page costs no edit of its own; `make cheatsheet` after a
# description change is the whole duty. Order is alphabetical, straight from the
# skills/ directory.
#
# `scripts/lint.sh` regenerates this into a temp file and diffs it against the
# committed page, so drift fails the gate instead of rotting quietly.
#
# Usage: scripts/cheatsheet.sh [--check|-o <path>]
#   (default: write docs/wiki/cheatsheet.md)
#   --check      write nothing; exit 1 if the committed page is out of date
#   -o <path>    write to <path> instead ( - for stdout )
# Kept bash 3.2 safe — no associative arrays, no `mapfile`.
set -euo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

OUT="$REPO_ROOT/docs/wiki/cheatsheet.md"

mode=write
while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) mode=check; shift ;;
    -o) OUT="$2"; shift 2 ;;
    *) die "unknown argument: $1 (usage: cheatsheet.sh [--check|-o <path>])" ;;
  esac
done

# The what-clause of a skill's description: the text before " Use when".
skill_summary() {
  local d
  d="$(description_text "$(frontmatter "$SKILLS_DIR/$1/SKILL.md")")"
  printf '%s\n' "${d%% Use when*}"
}

render() {
  local name summary

  cat <<'EOF'
# Cheatsheet

Every skill, one line each. This is the recall page, not the explanation. For how the skills compose into one loop, read [the workflow](./workflow.md). For a skill in full, follow its name to its `SKILL.md`.

| Skill | What it does |
|---|---|
EOF

  while IFS= read -r name; do
    [[ -z "$name" ]] && continue
    summary="$(skill_summary "$name" | sed 's/|/\\|/g')"
    printf -- '| [`%s`](../../skills/%s/SKILL.md) | %s |\n' "$name" "$name" "$summary"
  done < <(skill_names)

  cat <<'EOF'

---

_Generated by `make cheatsheet` from each skill's `description`. Edit the `SKILL.md`, not this file. `make lint` diffs the two._
EOF
}

# --- output ------------------------------------------------------------------

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
render > "$tmp"

if [[ "$mode" == check ]]; then
  if [[ ! -f "$OUT" ]]; then
    die "docs/wiki/cheatsheet.md is missing — run 'make cheatsheet'"
  fi
  if ! diff -u "$OUT" "$tmp" > /dev/null; then
    diff -u "$OUT" "$tmp" | sed 's/^/  /' >&2 || true
    die "docs/wiki/cheatsheet.md is out of date — run 'make cheatsheet'"
  fi
  info "docs/wiki/cheatsheet.md is up to date"
  exit 0
fi

if [[ "$OUT" == "-" ]]; then
  cat "$tmp"
else
  cat "$tmp" > "$OUT"
  info "wrote ${OUT#$REPO_ROOT/}"
fi
